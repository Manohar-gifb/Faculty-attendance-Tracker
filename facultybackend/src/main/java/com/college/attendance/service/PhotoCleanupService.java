package com.college.attendance.service;

import com.college.attendance.repository.UserRepository;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.scheduling.annotation.Scheduled;
import org.springframework.stereotype.Service;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.attribute.BasicFileAttributes;
import java.time.Duration;
import java.time.Instant;
import java.util.ArrayList;
import java.util.HashSet;
import java.util.List;
import java.util.Locale;
import java.util.Set;
import java.util.regex.Pattern;
import java.util.stream.Stream;

/**
 * Orphaned profile-photo lifecycle maintenance (FILE-04).
 *
 * Safety contract:
 *  1. A file referenced by ANY users.profile_picture_url row is NEVER deleted —
 *     active, deactivated, first-login-pending, or shared among several accounts.
 *  2. An unreferenced file younger than the retention/grace period is NEVER
 *     deleted (protects write-before-save crash windows and recent replacement
 *     uploads scanned before their superseded-prune ran).
 *  3. Files whose names do not match server-generated patterns are NEVER
 *     deleted, only reported — an operator file in the same directory survives.
 *  4. Enumeration is restricted to the approved upload directory; every
 *     delete re-asserts containment (see FileStorageService).
 *  5. Destructive deletion is DISABLED by default: the scheduled sweep and the
 *     developer run endpoint are dry-run until
 *     {@code app.photo-cleanup.deletion-enabled=true} is configured explicitly.
 */
@Service
@RequiredArgsConstructor
@Slf4j
public class PhotoCleanupService {

    /** UUID v4 textual form as generated by ImageFileValidator.safeFilename(). */
    private static final String HEX_UUID =
            "[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}";

    /**
     * Names the system itself ever generates (05-01 + legacy 8-hex fragment):
     *   <uuid>.<ext>          self-service uploads (05-01)
     *   user_<id>_<uuid>.<ext> developer uploads (05-01)
     *   user_<id>_<8hex>.<ext> legacy developer uploads (pre-05-01)
     * Anything else is never auto-deleted.
     */
    private static final Pattern MANAGED_NAME = Pattern.compile(
            "^(?:" + HEX_UUID + "|user_[0-9]+_(?:" + HEX_UUID + "|[0-9a-fA-F]{8}))" +
                    "\\.(?:jpg|jpeg|png|webp)$");

    private final FileStorageService fileStorageService;
    private final UserRepository userRepository;

    /** Destructive deletion stays disabled until an operator turns it on. */
    @Value("${app.photo-cleanup.deletion-enabled:false}")
    private boolean deletionEnabled;

    /** Grace window between becoming unreferenced and becoming deletable. */
    @Value("${app.photo-cleanup.retention-hours:24}")
    private long retentionHours;

    public boolean isDeletionEnabled() {
        return deletionEnabled;
    }

    public long getRetentionHours() {
        return retentionHours;
    }

    /** Immutable lifecycle scan result. */
    public record CleanupReport(
            Path directory,
            int totalFiles,
            int referencedProtected,
            int unrecognizedKept,
            int graceProtected,
            int orphanCandidates,
            List<String> orphanFilenames,
            boolean deletionAttempted,
            int deleted
    ) {
        public boolean isDryRun() {
            return !deletionAttempted;
        }
    }

    /** Pure dry-run lifecycle scan — deletes nothing regardless of configuration. */
    public CleanupReport report() {
        return scanAndSweep(false);
    }

    /**
     * Run the lifecycle sweep. {@code destructive} is honored only when the
     * deletion-enabled property is true; otherwise this is a dry-run report.
     */
    public CleanupReport runCleanup(boolean destructive) {
        return scanAndSweep(destructive && deletionEnabled);
    }

    /** Daily scheduled sweep (04:00 default). Dry-run unless deletion is enabled. */
    @Scheduled(cron = "${app.photo-cleanup.cron:0 0 4 * * *}")
    public void scheduledLifecycleSweep() {
        CleanupReport report = runCleanup(true);
        if (report.isDryRun()) {
            log.info("Profile photo lifecycle DRY RUN (enable app.photo-cleanup.deletion-enabled to delete): {} files, {} referenced, {} unrecognized, {} within grace, {} orphan candidates",
                    report.totalFiles(), report.referencedProtected(), report.unrecognizedKept(),
                    report.graceProtected(), report.orphanCandidates());
        } else {
            log.info("Profile photo lifecycle sweep deleted {} orphaned file(s) of {} orphan candidates (dir: {})",
                    report.deleted(), report.orphanCandidates(), report.directory());
        }
    }

    private CleanupReport scanAndSweep(boolean destructive) {
        Path dir = fileStorageService.getUploadDirectory();

        int totalFiles = 0;
        int referenced = 0;
        int unrecognized = 0;
        int graceProtected = 0;
        Set<String> referencedNames = referencedFilenames();
        List<String> orphans = new ArrayList<>();

        if (!Files.isDirectory(dir)) {
            log.warn("Photo cleanup cannot run: upload directory does not exist: {}", dir);
            return new CleanupReport(dir, 0, 0, 0, 0, 0, orphans, false, 0);
        }

        Instant cutoff = Instant.now().minus(Duration.ofHours(retentionHours));

        try (Stream<Path> listing = Files.list(dir)) {
            for (Path candidate : (Iterable<Path>) listing::iterator) {
                if (!Files.isRegularFile(candidate)) {
                    continue;
                }
                totalFiles++;
                String name = candidate.getFileName().toString();
                if (!MANAGED_NAME.matcher(name).matches()) {
                    unrecognized++;
                    continue;
                }
                if (referencedNames.contains(name.toLowerCase(Locale.ROOT))) {
                    referenced++;
                    continue;
                }
                BasicFileAttributes attrs;
                try {
                    attrs = Files.readAttributes(candidate, BasicFileAttributes.class);
                } catch (IOException e) {
                    log.warn("Photo cleanup could not stat {} (kept): {}", candidate, e.getMessage());
                    graceProtected++;
                    continue;
                }
                if (attrs.lastModifiedTime().toInstant().isAfter(cutoff)) {
                    graceProtected++;
                    continue;
                }
                orphans.add(name);
            }
        } catch (IOException e) {
            log.error("Photo cleanup could not list {}: {}", dir, e.getMessage());
            return new CleanupReport(dir, totalFiles, referenced, unrecognized, graceProtected, 0, orphans, false, 0);
        }

        int deleted = 0;
        boolean attempted = false;
        if (destructive && !orphans.isEmpty()) {
            attempted = true;
            for (String name : orphans) {
                try {
                    if (fileStorageService.deleteStoredProfilePicture(name)) {
                        deleted++;
                    }
                } catch (IOException | RuntimeException e) {
                    // One failing file must never abort the sweep nor leave the
                    // directory in a partial state we cannot recover from.
                    log.warn("Photo cleanup skipped file {} (kept): {}", name, e.getMessage());
                }
            }
        }

        CleanupReport report = new CleanupReport(dir, totalFiles, referenced, unrecognized,
                graceProtected, orphans.size(), orphans, attempted, deleted);
        log.debug("Photo cleanup scan (dir={}): total={} referenced={} unrecognized={} grace={} orphans={} deleted={}",
                dir, report.totalFiles(), report.referencedProtected(), report.unrecognizedKept(),
                report.graceProtected(), report.orphanCandidates(), report.deleted());
        return report;
    }

    /**
     * Prune the superseded previous photo of a user whose profile_picture_url
     * has just been saved pointing at a NEW file. Deletes only when:
     *   - the previous name is a system-generated managed name,
     *   - no user record (any account) still references that filename,
     *   - the file resolves inside the approved directory.
     * Never throws — callers treat pruning as best-effort hygiene.
     */
    public boolean pruneSupersededPhoto(String previousUrl, Long updatedUserId) {
        if (previousUrl == null || previousUrl.isBlank()) {
            return false;
        }

        String filename = previousUrl.replace('\\', '/');
        int lastSlash = filename.lastIndexOf('/');
        if (lastSlash >= 0) {
            filename = filename.substring(lastSlash + 1);
        }
        if (filename.isBlank()) {
            return false;
        }
        if (filename.contains("..")) {
            throw new SecurityException("Security violation: refusing to prune traversal path " + previousUrl);
        }
        if (!MANAGED_NAME.matcher(filename).matches()) {
            log.debug("Superseded photo name {} is not a system-generated file; leaving on disk", filename);
            return false;
        }

        Set<String> referencedNames = referencedFilenames();
        if (referencedNames.contains(filename)) {
            // Shared across accounts (or freshly re-referenced): protected.
            log.debug("Superseded photo {} is still referenced by an account record; kept", filename);
            return false;
        }

        try {
            boolean deleted = fileStorageService.deleteStoredProfilePicture(filename);
            if (deleted) {
                log.info("Pruned superseded profile photo {} (user {} moved to a new photo)", filename, updatedUserId);
            }
            return deleted;
        } catch (IOException e) {
            log.warn("Superseded photo {} could not be pruned (will be handled by the scheduled sweep): {}",
                    filename, e.getMessage());
            return false;
        }
    }

    /**
     * Filenames referenced by any account, extracted from the stored URL (last
     * path segment), normalized lowercase. Includes deactivated accounts by
     * design — their registered face photo must stay on disk.
     */
    public Set<String> referencedFilenames() {
        Set<String> names = new HashSet<>();
        for (String url : userRepository.findAllProfilePictureUrls()) {
            if (url == null || url.isBlank()) {
                continue;
            }
            String normalized = url.replace('\\', '/');
            int lastSlash = normalized.lastIndexOf('/');
            String filename = lastSlash >= 0 ? normalized.substring(lastSlash + 1) : normalized;
            if (!filename.isBlank()) {
                names.add(filename.toLowerCase(Locale.ROOT));
            }
        }
        return names;
    }
}
